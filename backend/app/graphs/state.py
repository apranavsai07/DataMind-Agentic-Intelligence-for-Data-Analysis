from typing import Any
from typing_extensions import TypedDict, Annotated
import operator


class WorkspaceState(TypedDict, total=False):

    # ========================================================
    # INPUT
    # ========================================================

    filename: str

    file_type: str

    user_request: str

    document: Any

    # ========================================================
    # DATA
    # ========================================================

    dataframe: Any

    document_text: str

    metadata: dict[str, Any]

    # ========================================================
    # PLANNER
    # ========================================================

    plan: list[dict[str, Any]]

    requires_report: bool

    # ========================================================
    # RESULTS
    # ========================================================

    results: dict[str, Any]

    # ========================================================
    # MESSAGES
    # ========================================================

    messages: Annotated[
        list,
        operator.add,
    ]

    # ========================================================
    # ARTIFACTS
    # ========================================================

    artifacts: list

    # ========================================================
    # CLEANING
    # ========================================================

    preprocessing_steps: list[str]

    # ========================================================
    # OUTPUT
    # ========================================================

    output_file: str | None

    # ========================================================
    # REPORT
    # ========================================================

    report: dict[str, Any]